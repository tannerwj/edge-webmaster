import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const webDir = path.join(root, "web");
const distDir = path.join(webDir, "dist");

execFileSync(path.join(root, "node_modules", ".bin", "vite"), ["build"], {
  cwd: webDir,
  stdio: "inherit",
});

let html = readFileSync(path.join(distDir, "index.html"), "utf8");

html = html.replace(/<link rel="stylesheet"[^>]*href="\.\/([^"]+)"[^>]*>/, (_m, file) => {
  const css = readFileSync(path.join(distDir, file), "utf8").replaceAll("</style", "<\\/style");
  return `<style>${css}</style>`;
});

html = html.replace(/<script type="module"[^>]*src="\.\/([^"]+)"[^>]*><\/script>/, (_m, file) => {
  const js = readFileSync(path.join(distDir, file), "utf8").replaceAll("</script", "<\\/script");
  return `<script type="module">${js}</script>`;
});

if (!html.includes("<style>") || !html.includes('<script type="module">')) {
  throw new Error("Failed to inline the built CSS/JS into the HTML document.");
}

const out = `// Generated by scripts/build-frontend.mjs — do not edit by hand.\nexport const UI_HTML = ${JSON.stringify(html)};\n`;
writeFileSync(path.join(root, "src", "frontend.gen.ts"), out);
console.log("Wrote src/frontend.gen.ts");
